saldo = 200
saque = 200

print(saldo == saque) 
print(saldo != saque)  # False, pois saldo é igual a saque
print(saldo > saque)   # False, pois saldo é igual a saque
print(saldo < saque)   # False, pois saldo é igual a saque
print(saldo >= saque)  # True, pois saldo é igual a saque
print(saldo <= saque)  # True, pois saldo é igual a saque